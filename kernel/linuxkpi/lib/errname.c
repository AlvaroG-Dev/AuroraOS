/* "-EXXX" o NULL si el numero no tiene nombre. */
const char *lkpi_errname(int err);
const char *lkpi_errname(int err)
{
	unsigned int e = err < 0 ? -err : err;
	if (e < ARRAY_SIZE(names_0))
		return names_0[e];
	if (e >= 512 && e - 512 < ARRAY_SIZE(names_512))
		return names_512[e - 512];
	return NULL;
}
