; kernel/isr_stubs.asm
; Stubs de ISR/IRQ que empujan estado y llaman a handlers en C

section .text
bits 64

%macro ISR_NOERR 1
global isr%1
isr%1:
    push 0          ; dummy error code
    push %1         ; ISR number
    jmp isr_common
%endmacro

%macro ISR_ERR 1
global isr%1
isr%1:
    push %1         ; ISR number (error code ya esta en stack)
    jmp isr_common
%endmacro

%macro IRQ 2
global irq%1
irq%1:
    push 0
    push %2
    jmp irq_common
%endmacro

